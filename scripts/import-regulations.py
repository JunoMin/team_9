"""Read the collected LH workbook; never modify it. Requires openpyxl.

python scripts/import-regulations.py <workbook.xlsx> --as-of YYYY-MM-DD
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

from openpyxl import load_workbook


def number(value):
    return float(value) if isinstance(value, (int, float)) else None


def ids(value):
    return [x.strip() for x in str(value or '').split(',') if x.strip()]


def url(value):
    value = str(value or '')
    match = re.match(r'=HYPERLINK\("([^"]+)"', value)
    target = match[1] if match else value
    # Only public source URLs are exported, never workstation paths.
    return target if target.startswith('https://apply.lh.or.kr/') else ''


def read_rows(workbook, sheet, headers):
    ws = workbook[sheet]
    actual = [cell.value for cell in ws[6]]
    for index, expected in headers.items():
        if actual[index] != expected:
            raise ValueError(f'{sheet}: column {index + 1} expected {expected}')
    return list(ws.iter_rows(min_row=7, values_only=True))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('workbook', type=Path)
    parser.add_argument('--as-of', required=True)
    args = parser.parse_args()
    from datetime import date
    date.fromisoformat(args.as_of)
    book = load_workbook(args.workbook, data_only=False)
    raw = read_rows(book, '선착순원본', {0: '지역', 1: '사업지구', 10: '면적(㎡)', 21: '원본 행', 24: '지구명 연관 공고 ID'})
    parcels = [dict(row=r[21], region=r[0], district=r[1], locality=r[2] or '',
                    plannedLot=r[3] or '', confirmedLot=r[4] or '', areaM2=number(r[10]),
                    use=r[6] or '', zoning=r[14] or '', coverage=number(r[15]),
                    floorArea=number(r[16]), floors=number(r[17]), noticeIds=ids(r[22]),
                    relatedNoticeIds=ids(r[24])) for r in raw]
    if len({p['row'] for p in parcels}) != len(parcels):
        raise ValueError('Duplicate source row IDs')
    if any(not p['region'] or not p['district'] or not p['areaM2'] for p in parcels):
        raise ValueError('Missing parcel identity')
    rows = read_rows(book, '필지목록', {1: '공고 ID', 4: '지번·획지(원문)', 13: '엑셀 원본 행'})
    notice_parcels = [dict(noticeId=r[1], lot=r[4], areaM2=number(r[6]), address=r[3], region=r[0], sourceRow=r[13]) for r in rows if r[1]]
    rows = read_rows(book, '공고목록', {1: '공고 ID', 12: '공고 URL'})
    notices = [dict(id=r[1], title=r[2], region=r[0], url=url(r[12]), status=r[5], collectionStatus=r[10], note=r[13] or '') for r in rows]
    rows = read_rows(book, '파일대장', {1: '공고 ID', 4: '원본 파일명·ZIP 내부명', 9: '다운로드 URL'})
    docs = [dict(noticeId=r[1], fileId=r[2], title=r[4], kind=r[3], url=url(r[9]), sha256=r[8] or '', inArchive='ZIP 내부' in r[3]) for r in rows if ('시행지침' in r[3] or '계획자료' in r[3]) and r[5] in ['완료', '압축해제 완료'] and url(r[9])]
    rows = read_rows(book, '규제정리_3건', {3: '공고 ID', 5: '해당 블록', 20: '시행지침 URL'})
    samples = [dict(noticeId=r[3], district=r[2], blocks=r[5], use=r[6], coverage=r[7] * 100, floorArea=r[8] * 100, floors=r[9], height=str(r[10]), allowed=r[11], prohibited=r[12], conditions=r[13], pdfPages=str(r[14]), printedPages=str(r[15]), article=r[16], verification=r[17], url=url(r[20])) for r in rows]
    data = dict(version=1, asOf=args.as_of, workbook=args.workbook.name, workbookSha256=hashlib.sha256(args.workbook.read_bytes()).hexdigest(), parcels=parcels, noticeParcels=notice_parcels, notices=notices, documents=docs, samples=samples)
    encoded = json.dumps(json.dumps(data, ensure_ascii=False, separators=(',', ':')), ensure_ascii=False)
    output = Path(__file__).resolve().parents[1] / 'src/data/regulations.generated.ts'
    output.write_text('// Generated by scripts/import-regulations.py. Do not edit.\nimport type { RegulationDataset } from "../types/regulations.ts"\nexport const regulationData: RegulationDataset = JSON.parse(' + encoded + ')\n', encoding='utf-8', newline='\n')
    print(json.dumps({k: len(data[k]) for k in ['parcels', 'noticeParcels', 'notices', 'documents', 'samples']}))


if __name__ == '__main__':
    main()
